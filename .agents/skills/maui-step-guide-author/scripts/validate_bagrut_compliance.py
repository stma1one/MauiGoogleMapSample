#!/usr/bin/env python3
"""
Validate-Bagrut-Compliance.py
-----------------------------
Cross-platform static declaration and checklist auditor for Ministry of Education 5-unit
Smartphone Programming (.NET MAUI - 883589) capstone requirements and separate AI code attribution rules.

IMPORTANT:
This script audits self-reported table declarations in `Learning/Bagrut-Compliance.md` and static
comment rules only. It NEVER outputs `PASS` and does NOT prove that the underlying C#/XAML code
is functionally or pedagogically valid. Actual implementation correctness requires live runtime
verification (e.g., via MAUI DevFlow / emulator testing) and instructor review.

Modes:
- Default (Progress Mode): Verifies that `PLANNED` + `IMPLEMENTED` items satisfy all 5-unit selection rules,
  prints a progress summary of remaining `PLANNED` items and optional enrichment suggestions, verifies
  `AI-And-External-Code-Attribution.md` exists, and checks that `.cs`/`.xaml` files contain no inline
  `// Generated by AI` comments.
- `--submission-ready`: Requires all selected rubric items to be marked `IMPLEMENTED` (zero `PLANNED` items
  remaining for required thresholds) and verifies cover-page metadata is filled in.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass


ROW_RE = re.compile(
    r"^\|\s*`([^`]+)`\s*\|\s*([^|]+?)\s*\|\s*`(NOT_SELECTED|PLANNED|IMPLEMENTED)`\s*\|\s*([^|]+?)\s*\|",
    re.MULTILINE,
)

FORBIDDEN_INLINE_AI_RE = re.compile(
    r"(//\s*(generated|written|created|authored)\s+by\s+(ai|chatgpt|claude|gemini|copilot|llm)\b|"
    r"<!--\s*(generated|written|created)\s+by\s+(ai|chatgpt|claude|gemini|copilot|llm)\b)",
    re.IGNORECASE,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Audit 5-unit Bagrut compliance declarations and AI attribution.")
    parser.add_argument("--project-root", default=str(Path(__file__).resolve().parent.parent), help="Project root path")
    parser.add_argument(
        "--submission-ready",
        action="store_true",
        help="Strict pre-submission declaration check: require IMPLEMENTED status (not just PLANNED) on all required items.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    project_root = Path(args.project_root).resolve()
    compliance_file = project_root / "Learning/Bagrut-Compliance.md"
    attribution_file = project_root / "Learning/AI-And-External-Code-Attribution.md"

    errors: list[str] = []
    notes: list[str] = []

    if not compliance_file.is_file():
        print(f"ERROR: Missing compliance file: {compliance_file}", file=sys.stderr)
        return 2

    if not attribution_file.is_file():
        errors.append(f"Missing separate AI attribution log: {attribution_file}")

    text = compliance_file.read_text(encoding="utf-8", errors="ignore")
    items: dict[str, dict[str, str]] = {}
    for match in ROW_RE.finditer(text):
        code, title, status, details = match.groups()
        items[code.strip()] = {
            "title": title.strip(),
            "status": status.strip(),
            "details": details.strip(),
        }

    allowed_statuses = {"IMPLEMENTED"} if args.submission_ready else {"PLANNED", "IMPLEMENTED"}
    mode_label = "SUBMISSION-READY DECLARATION CHECK (IMPLEMENTED ONLY)" if args.submission_ready else "PROGRESS DECLARATION CHECK (PLANNED + IMPLEMENTED)"

    def is_active(code: str) -> bool:
        return items.get(code, {}).get("status") in allowed_statuses

    # 1b. Verify that any item marked IMPLEMENTED specifies concrete file/class details (not template placeholders)
    for code, info in items.items():
        if info["status"] == "IMPLEMENTED":
            det = info["details"]
            if not det or det == "-" or "[למשל:" in det or "[ציינו" in det or "[TBD]" in det:
                errors.append(
                    f"Item {code} is marked IMPLEMENTED in Bagrut-Compliance.md but its implementation details column still contains a placeholder ({det!r})."
                )

    # 1. Threshold requirements REQ-1..REQ-4
    for req_id in ("REQ-1", "REQ-2", "REQ-3", "REQ-4"):
        if not is_active(req_id):
            errors.append(
                f"Threshold requirement {req_id} is not marked {'IMPLEMENTED' if args.submission_ready else 'PLANNED/IMPLEMENTED'}."
            )

    # 2. Section 5 AI: Must select at least 1 path from AI-1..AI-4 (one or more allowed)
    ai_ids = ("AI-1", "AI-2", "AI-3", "AI-4")
    active_ai = [aid for aid in ai_ids if is_active(aid)]
    all_selected_ai = [aid for aid in ai_ids if items.get(aid, {}).get("status") in {"PLANNED", "IMPLEMENTED"}]
    if len(active_ai) == 0:
        errors.append("Section 5 (AI): At least one AI path (AI-1..AI-4) must be selected.")
    elif len(all_selected_ai) == 1:
        notes.append(
            f"Section 5 (AI): 1 AI path selected ({all_selected_ai[0]}), which satisfies the mandatory threshold. "
            "Optional enrichment: you may suggest combining an additional AI path or extra Section 9/10 component if the student wants to expand."
        )
    else:
        notes.append(
            f"Section 5 (AI): {len(all_selected_ai)} AI paths selected ({all_selected_ai}) — exceeds minimum threshold (>=1). "
            "(Note: Section 5 AI counts as 1 topic toward Section 6 regardless of how many AI paths are implemented)."
        )

    # 3. Section 6: At least 2 topics (Section 5 AI counts as 1 topic)
    sec6_ids = ("6.1", "6.3", "6.4", "6.5", "6.7", "6.8", "6.9", "6.10", "6.11", "6.12")
    active_sec6 = [sid for sid in sec6_ids if is_active(sid)]
    total_sec6_with_ai = len(active_sec6) + (1 if active_ai else 0)
    if total_sec6_with_ai < 2:
        errors.append(
            f"Section 6: Need at least 2 topics (including Section 5 AI), found {total_sec6_with_ai}."
        )

    # 4. Section 7 Database: DB-Local or DB-Remote-Sync
    db_local = is_active("DB-Local")
    db_remote = is_active("DB-Remote-Sync")
    if not (db_local or db_remote):
        errors.append("Section 7 (Database): Must select at least DB-Local (SQLite) or DB-Remote-Sync (Firestore/RealtimeDB/MySQL).")

    # 5. Section 8 Advanced Topics:
    # Option 1: >= 3 from Section 9
    # Option 2: >= 2 from Section 9 AND >= 2 from Section 10 (DB-Remote-Sync counts as +2 in Section 10)
    sec9_ids = tuple(f"9.{i}" for i in range(1, 13))
    sec10_ids = ("10.1", "10.2", "10.3", "10.5", "10.6", "10.7", "10.8", "10.9", "10.10", "10.11", "10.12")
    active_sec9 = [sid for sid in sec9_ids if is_active(sid)]
    active_sec10 = [sid for sid in sec10_ids if is_active(sid)]
    effective_sec10_count = len(active_sec10) + (2 if db_remote else 0)

    option1_ok = len(active_sec9) >= 3
    option2_ok = len(active_sec9) >= 2 and effective_sec10_count >= 2
    if not (option1_ok or option2_ok):
        errors.append(
            f"Section 8 (Advanced Topics): Must have either >=3 topics from Section 9 (found {len(active_sec9)}) "
            f"OR (>=2 from Section 9 AND >=2 from Section 10; found Sec9={len(active_sec9)}, effective Sec10={effective_sec10_count})."
        )

    # 6. Pre-submission cover metadata check
    if args.submission_ready and "[TBD]" in text:
        errors.append("Pre-submission check: Cover page metadata in Bagrut-Compliance.md still contains '[TBD]' placeholders.")

    # 7. Check source code files for forbidden inline AI attribution comments
    source_files = [
        p for p in project_root.rglob("*")
        if p.is_file()
        and p.suffix.lower() in {".cs", ".xaml"}
        and "/bin/" not in p.as_posix()
        and "/obj/" not in p.as_posix()
        and "/Scripts/" not in p.as_posix()
    ]
    for src_file in source_files:
        src_text = src_file.read_text(encoding="utf-8", errors="ignore")
        for m in FORBIDDEN_INLINE_AI_RE.finditer(src_text):
            line_no = src_text[: m.start()].count("\n") + 1
            errors.append(
                f"Inline AI attribution comment found in {src_file.relative_to(project_root)}:{line_no} ({m.group(0)!r}). "
                "Record AI attribution exclusively in Learning/AI-And-External-Code-Attribution.md."
            )

    # Progress summary
    planned_items = [k for k, v in items.items() if v["status"] == "PLANNED"]
    implemented_items = [k for k, v in items.items() if v["status"] == "IMPLEMENTED"]

    print("=================================================")
    print(f" BAGRUT 5-UNIT CAPSTONE AUDIT ({mode_label})")
    print("=================================================")
    print(f"Selected AI Path(s):     {all_selected_ai or 'None'}")
    print(f"Section 6 Topics:        {len(active_sec6)} (+ {1 if active_ai else 0} AI) = {total_sec6_with_ai}")
    print(f"Section 7 Database:      {'DB-Remote-Sync (+2 Sec10 bonus)' if db_remote else ('DB-Local (SQLite)' if db_local else 'None')}")
    print(f"Section 9 Topics:        {len(active_sec9)} ({active_sec9})")
    print(f"Section 10 Topics:       {len(active_sec10)} (+ {2 if db_remote else 0} remote DB bonus) = {effective_sec10_count}")
    print(f"Status Breakdown:        {len(implemented_items)} IMPLEMENTED, {len(planned_items)} PLANNED")
    if planned_items and not args.submission_ready:
        print(f"Remaining PLANNED items: {', '.join(planned_items)}")
    print("")
    print("DISCLAIMER: This script audits self-reported table declarations in Bagrut-Compliance.md")
    print("            and static comment rules only. It does NOT verify or prove that the actual")
    print("            C#/XAML implementation is functionally correct or meets rubric quality standards.")
    print("")

    for nmsg in notes:
        print(f"[NOTE] {nmsg}")

    if errors:
        print("BAGRUT COMPLIANCE DECLARATION ISSUES:")
        for emsg in errors:
            print(f"  [ERROR] {emsg}")
        print("RESULT: DECLARATION_INCOMPLETE (Action Required)")
        return 1

    if args.submission_ready:
        print("RESULT: SUBMISSION_DECLARATION_OK (Static Checklist Only — Implementation correctness NOT proven; requires live runtime & teacher verification)")
    else:
        print("RESULT: DECLARATION_CHECK_OK (Static Checklist Only — Implementation correctness NOT proven; requires live runtime & teacher verification)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
